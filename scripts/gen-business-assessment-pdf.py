def kpi_table(data):
    """Render a table with header row styled. All cell content is wrapped in
    Paragraphs so long text wraps within the cell instead of overflowing."""
    cols = len(data[0])
    available = 170 * mm  # A4 width minus margins

    # Weight columns: first column gets more space if it's a label column
    if cols >= 3:
        # Give first column 30%, distribute rest evenly
        first_w = available * 0.30
        rest_w = (available - first_w) / (cols - 1)
        col_widths = [first_w] + [rest_w] * (cols - 1)
    else:
        col_widths = [available / cols] * cols

    # Wrap all cells in Paragraphs for proper text wrapping
    cell_style_header = ParagraphStyle(
        'cell_h', fontName=FONTS['heading_bold'], fontSize=8.5, leading=11,
        textColor=TABLE_HEADER_TEXT, alignment=TA_LEFT
    )
    cell_style_body = ParagraphStyle(
        'cell_b', fontName=FONTS['body'], fontSize=8.5, leading=11,
        textColor=TEXT_PRIMARY, alignment=TA_LEFT
    )

    wrapped_data = []
    for row_idx, row in enumerate(data):
        wrapped_row = []
        for cell in row:
            text = str(cell) if cell is not None else ''
            style = cell_style_header if row_idx == 0 else cell_style_body
            wrapped_row.append(Paragraph(text, style))
        wrapped_data.append(wrapped_row)

    t = Table(wrapped_data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [TABLE_ROW_EVEN, TABLE_ROW_ODD]),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.25, BORDER),
    ]))
    return t

def callout_box(title, body_text, bg=CARD_BG, border=ACCENT):
    """Render a callout box with title and body."""
    available = 170 * mm
    inner = [
        [Paragraph(f'<b>{title}</b>', ParagraphStyle('cb_title', fontName=FONTS['heading_bold'], fontSize=10, leading=14, textColor=border))],
        [Paragraph(body_text, ParagraphStyle('cb_body', fontName=FONTS['body'], fontSize=9.5, leading=14, textColor=TEXT_PRIMARY))]
    ]
    t = Table(inner, colWidths=[available])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), bg),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ('LINEBEFORE', (0, 0), (0, -1), 3, border),
    ]))
    return t

