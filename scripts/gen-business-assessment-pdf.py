def on_page(canvas, doc):
    """Header + footer on every body page."""
    canvas.saveState()
    width, height = A4

    # Footer
    canvas.setFont(FONTS['body'], 8)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(20 * mm, 12 * mm, 'RegGuard AI — Business Assessment & Investor Pitch')
    canvas.drawRightString(width - 20 * mm, 12 * mm, f'Page {doc.page}')
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.3)
    canvas.line(20 * mm, 15 * mm, width - 20 * mm, 15 * mm)

    # Header (skip on page 1 = cover)
    if doc.page > 1:
        canvas.setFont(FONTS['heading'], 8)
        canvas.setFillColor(TEXT_MUTED)
        canvas.drawRightString(width - 20 * mm, height - 12 * mm, 'Confidential — For Investor & Partner Review')
        canvas.setStrokeColor(BORDER)
        canvas.line(20 * mm, height - 15 * mm, width - 20 * mm, height - 15 * mm)

    canvas.restoreState()

